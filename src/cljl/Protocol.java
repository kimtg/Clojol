package cljl;

import cljl.lang.*;
import java.util.*;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.CopyOnWriteArrayList;

/**
 * Clojure Protocol descriptor and fast polymorphic class-based method dispatch table.
 */
public final class Protocol {
    public interface Dispatchable {
        Fn __protocolFn(Protocol p, Keyword methodKey);
        boolean __satisfies(Protocol p);
    }

    public final Symbol name;
    public final String doc;
    public final Class<?> onInterface;
    // Method name -> declared fixed arities (1..4) present on onInterface (null if no generated interface)
    public final Map<String, int[]> interfaceMethodArities;
    public final ConcurrentHashMap<Keyword, Fn> methodDefaults = new ConcurrentHashMap<>();
    // Set true if extend/extend-type overrides a class implementing onInterface or if protocol is redefined
    public volatile boolean hasInterfaceOverrides = false;
    // Monotonic epoch incremented on any impl/cache mutation for race-free PIC invalidation
    public volatile int epoch = 0;
    // Active MethodFns bound to this Protocol so addImpl/resetCaches eagerly clears their PIC slots
    private final CopyOnWriteArrayList<MethodFn> methodFns = new CopyOnWriteArrayList<>();
    // Protocol method Vars (e.g. #'calc) so an extend-type override on an inline record can swap to PIC dispatch
    private final CopyOnWriteArrayList<MethodVarEntry> methodVars = new CopyOnWriteArrayList<>();

    private record MethodVarEntry(Var var, Keyword key, String name) {}

    public void registerMethodVar(Var var, Keyword key, String name) {
        methodVars.add(new MethodVarEntry(var, key, name));
    }
    // Target Class<?> -> (methodName Keyword -> Fn)
    private final ConcurrentHashMap<Class<?>, ConcurrentHashMap<Keyword, Fn>> impls = new ConcurrentHashMap<>();
    // Cached resolved dispatch: Target Class<?> -> (methodName Keyword -> Fn or MISSING_IMPL)
    private final ConcurrentHashMap<Class<?>, ConcurrentHashMap<Keyword, Fn>> methodCache = new ConcurrentHashMap<>();
    private final ConcurrentHashMap<Class<?>, Boolean> satisfiesCache = new ConcurrentHashMap<>();
    // Special key for nil dispatch
    public static final Class<?> NIL_CLASS = Void.class;
    private static final Fn MISSING_IMPL = Fn.ofVarargs("protocol-missing", args -> {
        throw new IllegalStateException("Protocol missing sentinel invoked");
    });

    /**
     * Fast protocol method dispatcher base with a tear-free 2-entry Polymorphic Inline Cache (PIC).
     * Concrete per-method subclasses generated by TypeFactory override invoke/invokePrim_* with
     * dedicated monomorphic call sites for slot1 and slot2 so HotSpot C2 inlines both mono and
     * bimorphic dispatch targets without cross-protocol megamorphism.
     */
    public static class MethodFn extends Fn.NamedFn {
        public static final class CacheEntry {
            public final Class<?> cls;
            public final Fn fn;
            public CacheEntry(Class<?> cls, Fn fn) {
                this.cls = cls;
                this.fn = fn;
            }
        }

        protected final Var protoVar;
        protected final Keyword methodKey;
        public volatile CacheEntry slot1;
        public volatile CacheEntry slot2;
        private volatile Protocol registeredProto;

        public MethodFn(Var protoVar, Keyword methodKey, String name) {
            super(name);
            this.protoVar = protoVar;
            this.methodKey = methodKey;
        }

        public void invalidateCache() {
            this.slot1 = null;
            this.slot2 = null;
        }

        private Fn lookup(Object target) {
            Class<?> cls = (target != null) ? target.getClass() : NIL_CLASS;
            CacheEntry e1 = this.slot1;
            if (e1 != null && e1.cls == cls) {
                return e1.fn;
            }
            CacheEntry e2 = this.slot2;
            if (e2 != null && e2.cls == cls) {
                return e2.fn;
            }
            return resolveAndCache(target, cls);
        }

        public Fn resolveAndCache(Object target, Class<?> cls) {
            Protocol p = (Protocol) protoVar.deref();
            if (this.registeredProto != p) {
                p.registerMethodFn(this);
                this.registeredProto = p;
                this.slot1 = null;
                this.slot2 = null;
            }
            if (target instanceof Dispatchable d) {
                Fn df = d.__protocolFn(p, methodKey);
                if (df != null) return df;
            }
            int ep = p.epoch;
            Fn impl = p.resolveMethod(methodKey, target);
            if (impl instanceof Compiler.CompiledFn cf) {
                impl = cf.ensureJit();
            }
            if (!(target instanceof Dispatchable) && p.epoch == ep) {
                CacheEntry entry = new CacheEntry(cls, impl);
                CacheEntry cur1 = this.slot1;
                if (cur1 == null || cur1.cls == cls) {
                    this.slot1 = entry;
                } else {
                    this.slot2 = entry;
                }
                if (p.epoch != ep) {
                    invalidateCache();
                }
            }
            return impl;
        }

        @Override public Object invoke(Object a) { return lookup(a).invoke(a); }
        @Override public Object invoke(Object a, Object b) { return lookup(a).invoke(a, b); }
        @Override public Object invoke(Object a, Object b, Object c) { return lookup(a).invoke(a, b, c); }
        @Override public Object invoke(Object a, Object b, Object c, Object d) { return lookup(a).invoke(a, b, c, d); }
        @Override public long invokePrim_OJ_J(Object a, long b) { return lookup(a).invokePrim_OJ_J(a, b); }
        @Override public Object invokePrim_OJ_O(Object a, long b) { return lookup(a).invokePrim_OJ_O(a, b); }
        @Override public Object invokeVarargs(Object[] args) {
            if (args.length == 0) throw arityError(0);
            return lookup(args[0]).applyTo(args);
        }
    }

    void registerMethodFn(MethodFn mf) {
        methodFns.addIfAbsent(mf);
    }

    private void invalidateMethodFns() {
        for (MethodFn mf : methodFns) {
            mf.invalidateCache();
        }
    }

    public Protocol(Symbol name, String doc, Class<?> onInterface) {
        this(name, doc, onInterface, null);
    }

    public Protocol(Symbol name, String doc, Class<?> onInterface, Map<String, int[]> interfaceMethodArities) {
        this.name = name;
        this.doc = doc;
        this.onInterface = onInterface;
        this.interfaceMethodArities = interfaceMethodArities;
    }

    public void addImpl(Class<?> type, Map<Keyword, Fn> methods) {
        boolean swapToPic = false;
        if (onInterface != null && type != null && onInterface.isAssignableFrom(type) && !hasInterfaceOverrides) {
            hasInterfaceOverrides = true;
            swapToPic = true;
        }
        Class<?> key = (type == null) ? NIL_CLASS : type;
        ConcurrentHashMap<Keyword, Fn> map = impls.computeIfAbsent(key, k -> new ConcurrentHashMap<>());
        map.putAll(methods);
        methodCache.clear();
        satisfiesCache.clear();
        epoch++;
        invalidateMethodFns();
        if (swapToPic) {
            for (MethodVarEntry mve : methodVars) {
                Object cur = mve.var.getRawRoot();
                if (cur instanceof MethodFn mf && mf.protoVar != null && mf.protoVar.getRawRoot() == this) {
                    mve.var.bindRoot(TypeFactory.defineProtocolMethodFn(mf.protoVar, mve.key, mve.name, true));
                }
            }
        }
    }

    /** Registers direct defrecord/deftype implementations backed by onInterface without disabling fast interface dispatch. */
    public void addDirectImpl(Class<?> type, Map<Keyword, Fn> methods) {
        Class<?> key = (type == null) ? NIL_CLASS : type;
        ConcurrentHashMap<Keyword, Fn> map = impls.computeIfAbsent(key, k -> new ConcurrentHashMap<>());
        map.putAll(methods);
        methodCache.clear();
        satisfiesCache.clear();
        epoch++;
        invalidateMethodFns();
    }

    public void markRedefined() {
        hasInterfaceOverrides = true;
        resetCaches();
    }

    public boolean satisfies(Object x) {
        if (x == null) return impls.containsKey(NIL_CLASS);
        if (x instanceof Dispatchable d && d.__satisfies(this)) return true;
        return extendsType(x.getClass());
    }

    public boolean extendsType(Class<?> c) {
        if (c == null) return impls.containsKey(NIL_CLASS);
        Boolean cached = satisfiesCache.get(c);
        if (cached != null) return cached;
        boolean res = (onInterface != null && onInterface.isAssignableFrom(c)) || findImplMap(c) != null;
        satisfiesCache.putIfAbsent(c, res);
        return res;
    }

    public Collection<Class<?>> extenders() {
        List<Class<?>> out = new ArrayList<>();
        for (Class<?> c : impls.keySet()) {
            out.add(c == NIL_CLASS ? null : c);
        }
        return out;
    }

    private ConcurrentHashMap<Keyword, Fn> findImplMap(Class<?> c) {
        if (c == null) return impls.get(NIL_CLASS);
        ConcurrentHashMap<Keyword, Fn> direct = impls.get(c);
        if (direct != null) return direct;
        // Walk superclass chain (excluding Object), then interfaces, then Object
        for (Class<?> sup = c.getSuperclass(); sup != null && sup != Object.class; sup = sup.getSuperclass()) {
            ConcurrentHashMap<Keyword, Fn> m = impls.get(sup);
            if (m != null) return m;
        }
        for (Class<?> iface : collectInterfaces(c)) {
            ConcurrentHashMap<Keyword, Fn> m = impls.get(iface);
            if (m != null) return m;
        }
        return impls.get(Object.class);
    }

    private static List<Class<?>> collectInterfaces(Class<?> c) {
        List<Class<?>> result = new ArrayList<>();
        Set<Class<?>> seen = new HashSet<>();
        Deque<Class<?>> q = new ArrayDeque<>();
        for (Class<?> cur = c; cur != null; cur = cur.getSuperclass()) {
            for (Class<?> i : cur.getInterfaces()) {
                if (seen.add(i)) q.add(i);
            }
        }
        while (!q.isEmpty()) {
            Class<?> i = q.poll();
            result.add(i);
            for (Class<?> sup : i.getInterfaces()) {
                if (seen.add(sup)) q.add(sup);
            }
        }
        return result;
    }

    private Fn resolveUncached(Class<?> cls, Keyword methodKey) {
        if (cls == NIL_CLASS) {
            ConcurrentHashMap<Keyword, Fn> nilMap = impls.get(NIL_CLASS);
            if (nilMap != null) {
                Fn f = nilMap.get(methodKey);
                if (f != null) return f;
            }
            return methodDefaults.get(methodKey);
        }
        for (Class<?> cur = cls; cur != null && cur != Object.class; cur = cur.getSuperclass()) {
            ConcurrentHashMap<Keyword, Fn> m = impls.get(cur);
            if (m != null) {
                Fn f = m.get(methodKey);
                if (f != null) return f;
            }
        }
        for (Class<?> iface : collectInterfaces(cls)) {
            ConcurrentHashMap<Keyword, Fn> m = impls.get(iface);
            if (m != null) {
                Fn f = m.get(methodKey);
                if (f != null) return f;
            }
        }
        ConcurrentHashMap<Keyword, Fn> objMap = impls.get(Object.class);
        if (objMap != null) {
            Fn f = objMap.get(methodKey);
            if (f != null) return f;
        }
        return methodDefaults.get(methodKey);
    }

    public Fn resolveMethod(Keyword methodKey, Object target) {
        if (target instanceof Dispatchable d) {
            Fn df = d.__protocolFn(this, methodKey);
            if (df != null) return df;
        }
        Class<?> cls = (target == null) ? NIL_CLASS : target.getClass();
        ConcurrentHashMap<Keyword, Fn> cmap = methodCache.computeIfAbsent(cls, k -> new ConcurrentHashMap<>());
        Fn f = cmap.get(methodKey);
        if (f == null) {
            Fn resolved = resolveUncached(cls, methodKey);
            f = (resolved != null) ? resolved : MISSING_IMPL;
            cmap.putIfAbsent(methodKey, f);
        }
        if (f != MISSING_IMPL) return f;
        throw new IllegalArgumentException(
                "No implementation of method: " + methodKey + " of protocol: " + name
                        + " found for class: " + (cls == NIL_CLASS ? "nil" : cls.getName()));
    }

    public Fn resolveMethodOrNull(Keyword methodKey, Object target) {
        if (target instanceof Dispatchable d) {
            Fn df = d.__protocolFn(this, methodKey);
            if (df != null) return df;
        }
        Class<?> cls = (target == null) ? NIL_CLASS : target.getClass();
        ConcurrentHashMap<Keyword, Fn> cmap = methodCache.computeIfAbsent(cls, k -> new ConcurrentHashMap<>());
        Fn f = cmap.get(methodKey);
        if (f == null) {
            Fn resolved = resolveUncached(cls, methodKey);
            f = (resolved != null) ? resolved : MISSING_IMPL;
            cmap.putIfAbsent(methodKey, f);
        }
        return f != MISSING_IMPL ? f : null;
    }

    public PersistentHashMap findImplFor(Object target) {
        if (target instanceof Dispatchable d && d.__satisfies(this)) {
            return PersistentHashMap.EMPTY;
        }
        Class<?> cls = (target == null) ? NIL_CLASS : target.getClass();
        ConcurrentHashMap<Keyword, Fn> m = findImplMap(cls == NIL_CLASS ? null : cls);
        if (m == null) {
            if (cls != NIL_CLASS && onInterface != null && onInterface.isAssignableFrom(cls)) {
                return PersistentHashMap.EMPTY;
            }
            return null;
        }
        PersistentHashMap.TransientHashMap tm = PersistentHashMap.EMPTY.asTransient();
        for (Map.Entry<Keyword, Fn> e : m.entrySet()) {
            tm = tm.assoc(e.getKey(), e.getValue());
        }
        return tm.persistent();
    }

    public void resetCaches() {
        methodCache.clear();
        satisfiesCache.clear();
        epoch++;
        invalidateMethodFns();
    }

    @Override
    public String toString() {
        return "#<Protocol " + name + ">";
    }
}
